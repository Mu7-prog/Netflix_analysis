"""Outlier check"""

numeric_columns = netflix_df.select_dtypes(include=[np.number]).columns
for column in numeric_columns:

    Q1 = netflix_df[column].quantile(0.25)
    Q3 = netflix_df[column].quantile(0.75)
    IQR = Q3 - Q1
    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR

    outliers = netflix_df[(netflix_df[column] < lower_bound) | (netflix_df[column] > upper_bound)]

    print(f"\nColumn: {column}")
    print(f"Number of Outliers: {len(outliers)}")
    if len(outliers) > 0:
        print(outliers[[column]].describe())


    plt.figure(figsize=(8, 4))
    sns.boxplot(data=netflix_df, x=column)
    plt.title(f'Boxplot for {column} (Outlier Detection)')
    plt.show()

